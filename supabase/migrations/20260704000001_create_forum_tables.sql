-- 论坛系统数据库表结构
-- 创建时间：2026年7月4日

-- 论坛分类表
CREATE TABLE IF NOT EXISTS forum_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE, -- 分类名称：资源分享、学习讨论、反馈建议等
  description TEXT, -- 分类描述
  slug TEXT UNIQUE NOT NULL, -- URL友好的分类标识
  sort_order INTEGER DEFAULT 0, -- 排序权重
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  is_active BOOLEAN DEFAULT true -- 是否启用
);

-- 论坛帖子表
CREATE TABLE IF NOT EXISTS forum_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL, -- 帖子标题
  content TEXT NOT NULL, -- 帖子内容
  summary TEXT, -- 内容摘要
  category_id BIGINT REFERENCES forum_categories(id) ON DELETE SET NULL,
  author_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  post_type TEXT NOT NULL DEFAULT 'discussion', -- 帖子类型：discussion, resource, feedback
  resource_type TEXT, -- 资源类型：video, audio, article, document
  resource_url TEXT, -- 资源链接（用户提供的资源地址）
  resource_description TEXT, -- 资源描述
  tags TEXT[], -- 标签数组
  view_count INTEGER DEFAULT 0, -- 浏览量
  like_count INTEGER DEFAULT 0, -- 点赞数
  comment_count INTEGER DEFAULT 0, -- 评论数
  is_featured BOOLEAN DEFAULT false, -- 是否推荐
  is_pinned BOOLEAN DEFAULT false, -- 是否置顶
  status TEXT DEFAULT 'published', -- 状态：draft, published, moderating, rejected
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  published_at TIMESTAMPTZ,
  moderated_at TIMESTAMPTZ,
  moderator_id UUID REFERENCES auth.users(id)
);

-- 帖子封面图片（使用Supabase Storage）
CREATE TABLE IF NOT EXISTS post_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT REFERENCES forum_posts(id) ON DELETE CASCADE,
  image_url TEXT NOT NULL, -- Supabase Storage中的图片URL
  image_type TEXT DEFAULT 'cover', -- 图片类型：cover, content
  alt_text TEXT, -- 图片描述
  sort_order INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 帖子和资源点赞表
CREATE TABLE IF NOT EXISTS forum_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  post_id BIGINT REFERENCES forum_posts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, post_id) -- 防止重复点赞
);

-- 论坛评论表
CREATE TABLE IF NOT EXISTS forum_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT REFERENCES forum_posts(id) ON DELETE CASCADE,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  parent_id BIGINT REFERENCES forum_comments(id) ON DELETE CASCADE, -- 支持回复评论
  content TEXT NOT NULL,
  like_count INTEGER DEFAULT 0,
  status TEXT DEFAULT 'published', -- published, moderating, rejected
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  moderated_at TIMESTAMPTZ,
  moderator_id UUID REFERENCES auth.users(id)
);

-- 评论点赞表
CREATE TABLE IF NOT EXISTS comment_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  comment_id BIGINT REFERENCES forum_comments(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, comment_id)
);

-- 用户收藏表
CREATE TABLE IF NOT EXISTS user_favorites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  post_id BIGINT REFERENCES forum_posts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, post_id)
);

-- 论坛通知表
CREATE TABLE IF NOT EXISTS forum_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  type TEXT NOT NULL, -- 通知类型：like, comment, reply, mention
  title TEXT NOT NULL,
  content TEXT,
  post_id BIGINT REFERENCES forum_posts(id),
  comment_id BIGINT REFERENCES forum_comments(id),
  from_user_id UUID REFERENCES auth.users(id),
  is_read BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 反馈和建议表
CREATE TABLE IF NOT EXISTS user_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  feedback_type TEXT NOT NULL, -- bug, feature, content, general
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  priority TEXT DEFAULT 'medium', -- low, medium, high, urgent
  status TEXT DEFAULT 'open', -- open, in_progress, resolved, closed
  admin_response TEXT,
  admin_id UUID REFERENCES auth.users(id),
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  resolved_at TIMESTAMPTZ
);

-- 用户论坛配置表
CREATE TABLE IF NOT EXISTS user_forum_preferences (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email_notifications BOOLEAN DEFAULT true, -- 邮件通知
  push_notifications BOOLEAN DEFAULT true, -- 推送通知
  show_email BOOLEAN DEFAULT false, -- 公开邮箱
  bio TEXT, -- 个人简介
  signature TEXT, -- 签名档
  avatar_url TEXT, -- 头像URL
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 论坛统计表（定期更新）
CREATE TABLE IF NOT EXISTS forum_stats (
  id INTEGER PRIMARY KEY DEFAULT 1,
  total_posts INTEGER DEFAULT 0,
  total_comments INTEGER DEFAULT 0,
  total_users INTEGER DEFAULT 0,
  active_users_week INTEGER DEFAULT 0,
  active_users_month INTEGER DEFAULT 0,
  last_updated TIMESTAMPTZ DEFAULT now()
);


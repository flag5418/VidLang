-- forum_categories 策略：所有人可读取，只有管理员可修改
CREATE POLICY "Everyone can read categories" ON forum_categories
  FOR SELECT USING (is_active = true);

CREATE POLICY "Admin can manage categories" ON forum_categories
  FOR ALL USING (auth.uid() IN (
    SELECT id FROM auth.users WHERE raw_user_meta_data->>'role' = 'admin'
  ));

-- forum_posts 策略
CREATE POLICY "Everyone can read published posts" ON forum_posts
  FOR SELECT USING (status = 'published');

CREATE POLICY "Users can create posts" ON forum_posts
  FOR INSERT WITH CHECK (auth.uid() = author_id);

CREATE POLICY "Users can update own posts" ON forum_posts
  FOR UPDATE USING (auth.uid() = author_id);

CREATE POLICY "Admins can moderate posts" ON forum_posts
  FOR ALL USING (auth.uid() IN (
    SELECT id FROM auth.users WHERE raw_user_meta_data->>'role' = 'admin'
  ));

-- post_images 策略
CREATE POLICY "Everyone can read post images" ON post_images
  FOR SELECT USING (true);

CREATE POLICY "Users can manage own post images" ON post_images
  FOR ALL USING (
    EXISTS (
      SELECT 1 FROM forum_posts 
      WHERE forum_posts.id = post_images.post_id 
      AND forum_posts.author_id = auth.uid()
    )
  );

-- forum_likes 策略
CREATE POLICY "Everyone can read likes" ON forum_likes
  FOR SELECT USING (true);

CREATE POLICY "Users can create likes" ON forum_likes
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can delete own likes" ON forum_likes
  FOR DELETE USING (auth.uid() = user_id);

